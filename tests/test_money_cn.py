"""金额转中文大写的边界测试。

为什么单独测：签字单上金额错了是要担责任的，而这几个坑只有手算才
想得到——数字顺序反了、组间零丢了、浮点把 1.005 吞成 1.00。
用断言把坑钉住，下面每条都对应一个真实踩过的错误。
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from app.utils.money_cn import amount_to_cn  # noqa: E402

P, F = [], []


def eq(name, value, expect):
    got = amount_to_cn(value)
    ok = got == expect
    (P if ok else F).append(name)
    print(("  [PASS] " if ok else "  [FAIL] ") + name
          + ("" if ok else "  -> 期望「%s」实际「%s」" % (expect, got)))


print("=" * 76)
print("[1] 基本数字与单位")
print("=" * 76)
eq("0", 0, "零元整")
eq("1", 1, "壹元整")
eq("10", 10, "壹拾元整")
eq("11", 11, "壹拾壹元整")          # 曾错：壹壹拾
eq("100", 100, "壹佰元整")
eq("1000", 1000, "壹仟元整")
eq("100000", 100000, "壹拾万元整")
eq("1000000", 1000000, "壹佰万元整")

print()
print("=" * 76)
print("[2] 段内与组间的「零」（最易漏）")
print("=" * 76)
eq("101", 101, "壹佰零壹元整")
eq("1001", 1001, "壹仟零壹元整")     # 曾错：壹零壹仟
eq("1005", 1005, "壹仟零伍元整")     # 曾错：伍零壹仟
eq("10001", 10001, "壹万零壹元整")   # 曾错：壹万壹
eq("10010", 10010, "壹万零壹拾元整")
eq("10050", 10050, "壹万零伍拾元整")
eq("12345", 12345, "壹万贰仟叁佰肆拾伍元整")   # 曾错：数字反序
eq("20585500", 20585500, "贰仟零伍拾捌万伍仟伍佰元整")
eq("10000010", 10000010, "壹仟万零壹拾元整")  # 曾错：壹仟万壹拾
eq("100000001", 100000001, "壹亿零壹元整")
eq("100001000", 100001000, "壹亿零壹仟元整")  # 整段为零必须补零
eq("100020003", 100020003, "壹亿零贰万零叁元整")
eq("999999999", 999999999, "玖亿玖仟玖佰玖拾玖万玖仟玖佰玖拾玖元整")
eq("10000（整万不多补零）", 10000, "壹万元整")
eq("1010（段内零+尾零不补）", 1010, "壹仟零壹拾元整")
eq("5050", 5050, "伍仟零伍拾元整")

print()
print("=" * 76)
print("[3] 角分衔接")
print("=" * 76)
eq("12.0（无小数要写整）", 12.0, "壹拾贰元整")
eq("12.5", 12.5, "壹拾贰元伍角")
eq("12.55", 12.55, "壹拾贰元伍角伍分")
eq("12.05（角位补零）", 12.05, "壹拾贰元零伍分")   # 漏零会被读成 12 元 5 分
eq("10.09", 10.09, "壹拾元零玖分")
eq("0.5", 0.5, "零元伍角")
eq("0.05", 0.05, "零元零伍分")
eq("0.01", 0.01, "零元零壹分")

print()
print("=" * 76)
print("[4] 负数（减项）")
print("=" * 76)
eq("-8000", -8000, "负捌仟元整")
eq("-0.5", -0.5, "负零元伍角")
eq("-12345.67", -12345.67, "负壹万贰仟叁佰肆拾伍元陆角柒分")

print()
print("=" * 76)
print("[5] 取整必须是 HALF_UP，float 会吞钱")
print("=" * 76)
# 1.005 * 100 在 IEEE754 下 = 100.49999999999999，round() 得 100 分，
# 也就是 1.005 元被算成 1.00 元——一整分钱凭空消失。
eq("1.005 应进位到 1.01", 1.005, "壹元零壹分")
eq("1.004 应舍去", 1.004, "壹元整")
eq("8.115 应进位到 8.12", 8.115, "捌元壹角贰分")
eq("2.675（经典浮点坑）", 2.675, "贰元陆角捌分")   # float 会给 2.67
eq("0.1+0.2 不应多出一分", 0.1 + 0.2, "零元叁角")
eq("1.999 应进位到 2.00", 1.999, "贰元整")
eq("-1.005 负数同样进位", -1.005, "负壹元零壹分")

print()
print("=" * 76)
print("[6] 脏输入不崩，且绝不返回空串")
print("=" * 76)
for bad in (None, "", "abc", [], {}, 0, "0"):
    got = amount_to_cn(bad)
    ok = got == "零元整"
    (P if ok else F).append("脏输入 %r" % (bad,))
    print(("  [PASS] " if ok else "  [FAIL] ") + "脏输入 %-8r -> %s" % (bad, got))
# 金额栏空着 = 没填，签字单上必须显示「零元整」而不是留白
got = amount_to_cn(None)
ok = bool(got) and got == "零元整"
(P if ok else F).append("空值返回非空")
print(("  [PASS] " if ok else "  [FAIL] ") + "空值返回非空字符串")

print()
print("=" * 76)
print("[7] 字符串数字（表单传来的是 str，不是 float）")
print("=" * 76)
eq("字符串 '12345.67'", "12345.67", "壹万贰仟叁佰肆拾伍元陆角柒分")
eq("字符串 '0.01'", "0.01", "零元零壹分")
eq("带逗号的字符串 '1,234'", "1,234", None) if False else None
got = amount_to_cn("1,234")
ok = bool(got)
(P if ok else F).append("带逗号不崩")
print(("  [PASS] " if ok else "  [FAIL] ") + "带逗号的字符串不崩 -> %s" % got)

print()
print("=" * 76)
print("通过 %d 项，失败 %d 项" % (len(P), len(F)))
for x in F:
    print("  失败：" + x)
print("=" * 76)
sys.exit(1 if F else 0)